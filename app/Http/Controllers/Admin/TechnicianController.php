    /** 🔹 Update technician */
    public function update(Request $request, Technician $technician)
    {
        $validated = $request->validate([
            'full_name'        => 'required|string|max:255',
            'email'            => 'required|email|unique:technicians,email,' . $technician->id . ($technician->user_id ? '|unique:users,email,' . $technician->user_id : ''),
            'phone'            => 'nullable|string|max:20',
            'address'          => 'nullable|string|max:255',
            'service_area'     => 'nullable|string|max:255',
            'date_hire'        => 'nullable|date',
            'specialization'   => 'nullable|string|max:255',
            'emergency_name'   => 'nullable|string|max:255',
            'emergency_phone'  => 'nullable|string|max:20',
            'status'           => 'required|in:active,inactive,suspended',
            'profile_picture'  => 'nullable|image|max:2048',
        ]);

        // Profile picture upload
        if ($request->hasFile('profile_picture')) {
            $path = $request->file('profile_picture')->store('technicians', 'public');

            if ($technician->profile_picture && $technician->profile_picture !== 'images/default-avatar.png') {
                Storage::disk('public')->delete($technician->profile_picture);
            }

            $validated['profile_picture'] = $path;
        }

        $technician->update($validated);

        // Update user account email if changed
        if ($technician->wasChanged('email') && $technician->user) {
            $technician->user->update(['email' => $validated['email']]);
            Log::info("Updated user email for technician: {$technician->id}");
        }

        // If address was updated and geocoding might be needed
        if ($technician->wasChanged('address') && !empty($technician->address)) {
            Log::info("Address changed, re-geocoding for technician: {$technician->id}");
            $technician->geocodeAddress();
        }

        // Handle deactivation/reactivation based on status
        if ($validated['status'] === 'inactive') {
            $technician->user->deactivate();

            // Cancel or reassign active technician jobs
            $technician->technicianJobs()
                ->whereIn('status', ['assigned', 'in_progress'])
                ->update(['status' => 'cancelled']);
        } elseif ($validated['status'] === 'active' && $technician->user->isDeactivated()) {
            $technician->user->reactivate();
        }

        $message = 'Technician updated successfully!';

        // Check if password reset is confirmed
        if ($request->has('send_password') && $request->send_password) {
            // Generate a new random password
            $newPassword = Str::random(10);

            // Update user account with new password
            $technician->user->update([
                'password' => \Illuminate\Support\Facades\Hash::make($newPassword),
            ]);

            // Send the new password to the technician's email
            try {
                \Illuminate\Support\Facades\Mail::to($technician->user->email)->send(new \App\Mail\SendPasswordMail($technician->user->email, $newPassword, $technician->user->name));
                $message = 'Technician updated successfully and new password sent to email!';
            } catch (\Exception $e) {
                Log::error("Failed to send password email to technician {$technician->id}: {$e->getMessage()}");
                $message = 'Technician updated successfully, but failed to send password email.';
            }
        }

        return redirect()
            ->route('technicians.index')
            ->with('success', $message);
    }

