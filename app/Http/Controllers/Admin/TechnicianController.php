    /**
     * Send a new auto-generated password to the technician's email.
     */
    public function sendPasswordReset($id)
    {
        $technician = Technician::findOrFail($id);

        // Check if technician has associated user
        if (!$technician->user) {
            if (request()->ajax()) {
                return response()->json([
                    'success' => false,
                    'message' => 'Technician does not have an associated user account.'
                ], 400);
            }
            return redirect()->back()->with('error', 'Technician does not have an associated user account.');
        }

        // Generate a new random password
        $newPassword = \Illuminate\Support\Str::random(10);

        // Update the technician's password
        $technician->user->update([
            'password' => \Illuminate\Support\Facades\Hash::make($newPassword),
        ]);

        // Send email with the new password
        try {
            \Illuminate\Support\Facades\Mail::to($technician->user->email)
                ->send(new \App\Mail\SendPasswordMail($technician->user->email, $newPassword, $technician->user->name));

            $message = 'New password has been sent to the technician\'s email address.';
        } catch (\Exception $e) {
            Log::error("Failed to send password email to technician {$technician->id}: {$e->getMessage()}");

            if (request()->ajax()) {
                return response()->json([
                    'success' => false,
                    'message' => 'Password updated but failed to send email. Please try again.'
                ], 500);
            }
            return redirect()->back()->with('error', 'Password updated but failed to send email. Please try again.');
        }

        // Check if request is AJAX
        if (request()->ajax()) {
            return response()->json([
                'success' => true,
                'message' => $message
            ]);
        }

        return redirect()->back()->with('success', $message);
    }
}
