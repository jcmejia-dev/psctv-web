    public function store(Request $request)
    {
        $request->validate([
            'name' => 'required|string|max:255',
            'email' => 'required|email|unique:users,email',
            'status' => 'required|in:active,inactive,suspended,pending',
            'barangay' => 'required|string|max:255',
            // Remove 'password' validation since we auto-generate it
        ]);

        try {
            DB::transaction(function () use ($request) {
                // Step 2: Generate a random password
                $password = \Illuminate\Support\Str::random(10); // 10-character password

                // Step 3: Create the user with the autogenerated password
                $user = \App\Models\User::create([
                    'name' => $request->name,
                    'email' => $request->email,
                    'password' => Hash::make($password),
                    'role' => 'customer',
                ]);

                // Generate unique account number
                $accountNumber = $this->generateAccountNumber();

                // Step 3 (continued): Create customer record
                Customer::create([
                    'user_id' => $user->id,
                    'account_number' => $accountNumber,
                    'status' => $request->status,
                    'region' => $request->region,
                    'province' => $request->province,
                    'municipality' => $request->municipality,
                    'barangay' => $request->barangay,
                    'street' => $request->street,
                    'zip_code' => $request->zip_code,
                    'latitude' => $request->latitude,
                    'longitude' => $request->longitude,
                    'phone' => $request->phone,
                    'dob' => $request->dob,
                    'gender' => $request->gender,
                    'address' => $request->street ? $request->street . ', ' . $request->barangay : null,
                    'city' => $request->municipality,
                ]);

                // Step 4: Send password to user's email
               \Mail::to($user->email)->send(new \App\Mail\SendPasswordMail($user->email, $password, $user->name));

            });

            return redirect()->route('customers.list')->with('success', 'Customer created successfully and password sent to email.');
        } catch (\Throwable $e) {
            return back()->withErrors(['error' => 'Error creating customer: ' . $e->getMessage()]);
        }
    }

    private function generateAccountNumber()
    {
        do {
            $accountNumber = 'ACC-' . strtoupper(substr(md5(uniqid(mt_rand(), true)), 0, 6));
        } while (Customer::where('account_number', $accountNumber)->exists());

        return $accountNumber;
    }

