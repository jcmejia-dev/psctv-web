    /**
     * Send a new auto-generated password to the customer's email.
     */
    public function sendPasswordReset($id)
    {
        $customer = Customer::findOrFail($id);

        // Generate a new random password
        $newPassword = \Illuminate\Support\Str::random(10);

        // Update the customer's password
        $customer->user->update([
            'password' => \Illuminate\Support\Facades\Hash::make($newPassword),
        ]);

        // Send email with the new password
        \Illuminate\Support\Facades\Mail::to($customer->user->email)
            ->send(new \App\Mail\SendPasswordMail($customer->user->email, $newPassword, $customer->user->name));

        // Check if request is AJAX
        if (request()->ajax()) {
            return response()->json([
                'success' => true,
                'message' => 'New password has been sent to the customer\'s email address.'
            ]);
        }

        return redirect()->back()->with('success', 'New password has been sent to the customer\'s email address.');
    }
