                ];
            });

        return view('customers.view', compact('customer', 'formattedSubscriptions', 'formattedBilling', 'formattedRequests'));
    }

    public function update(Request $request, Customer $customer)
    {
        $request->validate([
            'name'   => 'required|string|max:255',
            'email'  => 'required|email|unique:users,email,' . $customer->user_id,
            'status' => 'required|in:active,inactive,suspended,pending',
        ]);

        try {
            DB::transaction(function () use ($request, $customer) {
                $customer->user->update([
                    'name'  => $request->name,
                    'email' => $request->email,
                ]);

                $customer->update([
                    'status'      => $request->status,
                    'region'      => $request->region,
                    'province'    => $request->province,
                    'municipality' => $request->municipality,
                    'barangay'    => $request->barangay,
                    'street'      => $request->street,
                    'zip_code'    => $request->zip_code,
                    'latitude'    => $request->latitude,
                    'longitude'   => $request->longitude,
                    'phone'       => $request->phone,
                    'dob'         => $request->dob,
                    'gender'      => $request->gender,
                ]);

                // Handle deactivation/reactivation based on status
                if ($request->status === 'inactive') {
                    $customer->user->deactivate();

                    // Suspend all active subscriptions for the customer
                    $customer->subscriptions()
                        ->where('service_status', 'active')
                        ->update(['service_status' => 'suspended']);
                } elseif ($request->status === 'active' && $customer->user->isDeactivated()) {
                    $customer->user->reactivate();

                    // Reactivate suspended subscriptions for the customer
                    $customer->subscriptions()
                        ->where('service_status', 'suspended')
                        ->update(['service_status' => 'active']);
                }
            });

            return redirect()->route('customers.list')->with('success', 'Customer updated successfully.');
        } catch (\Throwable $e) {
            return back()->withErrors(['error' => 'Error updating customer: ' . $e->getMessage()]);
        }
    }

    /** 🔹 Delete customer with confirmation */
    public function destroy(Customer $customer)
    {
        try {
            DB::transaction(function () use ($customer) {
                // Delete customer's user account
                if ($customer->user) {
                    $customer->user()->delete();
                }
                
                // Delete customer record
                $customer->delete();
            });

            // Check if this is an AJAX request
            if (request()->expectsJson() || request()->ajax()) {
                return response()->json([
                    'success' => true,
                    'message' => 'Customer deleted successfully!'
                ]);
            }

            // For regular form submissions, redirect back
            return redirect()
                ->route('customers.list')
                ->with('success', 'Customer deleted successfully!');

        } catch (\Exception $e) {
            \Illuminate\Support\Facades\Log::error("Failed to delete customer #{$customer->id}: {$e->getMessage()}");

            // Check if this is an AJAX request
            if (request()->expectsJson() || request()->ajax()) {
                return response()->json([
                    'success' => false,
                    'message' => 'Failed to delete customer. Please try again.'
                ], 500);
            }

            // For regular form submissions, redirect back with error
            return redirect()
                ->route('customers.list')
                ->with('error', 'Failed to delete customer. Please try again.');
        }
    }

